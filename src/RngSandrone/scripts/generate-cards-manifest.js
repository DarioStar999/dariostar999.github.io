const fs = require("fs");
const path = require("path");

const projectRoot = path.resolve(__dirname, "..");
const cardsRoot = path.join(projectRoot, "src", "assets", "cards");
const outputFile = path.join(projectRoot, "src", "js", "cards-manifest.js");
const imageExtensions = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif"]);
const includedRarities = ["r1", "r2", "r3", "r4", "r5", "r6"];

function rarityValue(rarity) {
    const match = rarity.match(/\d+/);
    return match ? Number(match[0]) : 0;
}

function toWebPath(filePath) {
    return path.relative(projectRoot, filePath).replace(/\\/g, "/");
}

function buildManifest() {
    const rarities = Object.fromEntries(includedRarities.map((rarity) => [rarity, []]));

    if (!fs.existsSync(cardsRoot)) {
        throw new Error(`Cards folder not found: ${cardsRoot}`);
    }

    for (const rarity of includedRarities) {
        const rarityFolder = path.join(cardsRoot, rarity);

        if (!fs.existsSync(rarityFolder)) {
            fs.mkdirSync(rarityFolder, { recursive: true });
        }

        const cards = fs.readdirSync(rarityFolder, { withFileTypes: true })
            .filter((file) => file.isFile() && imageExtensions.has(path.extname(file.name).toLowerCase()))
            .map((file) => {
                const filePath = path.join(rarityFolder, file.name);
                return {
                    id: `${rarity}-${path.parse(file.name).name}`,
                    name: path.parse(file.name).name,
                    rarity,
                    rarityLevel: rarityValue(rarity),
                    image: toWebPath(filePath),
                };
            })
            .sort((a, b) => a.name.localeCompare(b.name));

        rarities[rarity] = cards;
    }

    return {
        generatedAt: new Date().toISOString(),
        rarities: Object.keys(rarities)
            .sort((a, b) => rarityValue(a) - rarityValue(b) || a.localeCompare(b))
            .reduce((acc, rarity) => {
                acc[rarity] = rarities[rarity];
                return acc;
            }, {}),
    };
}

const manifest = buildManifest();
const contents = `// Auto-generated by scripts/generate-cards-manifest.js\n` +
    `// Run: node scripts/generate-cards-manifest.js\n` +
    `window.CARD_DATABASE = ${JSON.stringify(manifest, null, 4)};\n`;

fs.writeFileSync(outputFile, contents, "utf8");

const cardCount = Object.values(manifest.rarities).reduce((total, cards) => total + cards.length, 0);
console.log(`Generated ${toWebPath(outputFile)} with ${cardCount} cards.`);
